import { test, expect } from '@playwright/test'
import { mkdirSync } from 'node:fs'
test('A/B execution, regression evidence, immutable report and responsive layout',async({page})=>{
  const errors:string[]=[]
  page.on('pageerror',e=>errors.push(e.message))
  await page.goto('/')
  await page.getByRole('button',{name:'进入工作空间'}).click()
  await expect(page.getByRole('heading',{name:'每一次迭代，都看得见。'})).toBeVisible()
  await page.getByRole('button',{name:'运行 A/B 演示',exact:true}).click()
  await expect(page.getByRole('heading',{name:'每一次运行，都保留证据'})).toBeVisible()
  await expect(page.locator('tbody tr').first()).toContainText('完成 · 含异常',{timeout:40000})
  await expect(page.locator('tbody tr').nth(1)).toContainText('完成 · 含异常',{timeout:40000})
  await page.getByRole('button',{name:'版本对比',exact:true}).click()
  await page.getByRole('button',{name:'开始对比',exact:true}).click()
  await expect(page.getByText('+22.7 pp')).toBeVisible()
  await page.getByRole('button',{name:'退化',exact:true}).click()
  await expect(page.locator('tbody tr')).toHaveCount(1)
  await page.getByRole('button',{name:'B 详情'}).click()
  await expect(page.getByRole('heading',{name:'怎么修改管理员？'})).toBeVisible()
  await expect(page.getByText('回答缺少业务要点：原管理员；回答缺少业务要点：确认',{exact:true})).toBeVisible()
  mkdirSync('../docs/screenshots',{recursive:true})
  await page.screenshot({path:'../docs/screenshots/case-evidence.png',fullPage:true})
  await page.getByRole('button',{name:'关闭弹窗'}).click()
  await page.getByRole('button',{name:'生成验收报告'}).click()
  await page.getByRole('button',{name:'生成并预览'}).click()
  await expect(page.getByRole('heading',{name:'离线报告预览'})).toBeVisible()
  await expect(page.frameLocator('iframe').getByRole('heading',{name:'Agent 版本验收报告'})).toBeVisible()
  await page.getByRole('button',{name:'关闭弹窗'}).click()
  const download=page.waitForEvent('download')
  await page.getByRole('button',{name:'下载 HTML'}).first().click()
  await (await download).saveAs('../docs/sample-report.html')
  await page.getByRole('button',{name:'项目概览',exact:true}).click()
  await expect(page.locator('.toast')).toHaveCount(0)
  await page.screenshot({path:'../docs/screenshots/overview-desktop.png',fullPage:true})
  await page.setViewportSize({width:390,height:844})
  await page.screenshot({path:'../docs/screenshots/overview-mobile.png',fullPage:true})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy()
  expect(errors).toEqual([])
})
test('reviewer cannot create a run and outsider only sees own project',async({page})=>{
  await page.goto('/')
  await page.locator('select').selectOption('reviewer')
  await page.getByRole('button',{name:'进入工作空间'}).click()
  await expect(page.getByRole('heading',{name:'每一次迭代，都看得见。'})).toBeVisible()
  await expect(page.getByRole('button',{name:'新建评测'})).toHaveCount(0)
  await page.getByRole('button',{name:'退出登录'}).click()
  await page.locator('select').selectOption('outsider')
  await page.getByRole('button',{name:'进入工作空间'}).click()
  await expect(page.getByLabel('选择项目')).toHaveValue('project-private')
  await expect(page.getByRole('button',{name:'运行 A/B 演示'})).toHaveCount(0)
})
